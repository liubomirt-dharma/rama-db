"""Build the GitHub Pages site from the public data in assets/catalog.js."""
import argparse
from collections import Counter, defaultdict
from concurrent.futures import ThreadPoolExecutor
from datetime import date
from html import escape
from io import BytesIO
import json
from pathlib import Path
import re
import shutil
from urllib.parse import urlsplit
from urllib.request import urlopen
from urllib.error import HTTPError
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
BASE = "https://liubomirt-dharma.github.io/rama-db/"
PATH = urlsplit(BASE).path
SITE = "Центр изучения варнашрамы «Рама»"
HOME_TITLE = SITE + " — Библиотека видео"
HOME_DESC = ("Тематическая видеотека Центра изучения варнашрамы «Рама». Лекции и семинары о сознании Кришны, "
             "дхарме, варнашраме, философии Шрилы Прабхупады и общественных вопросах. Поиск по темам и тайм-кодам.")
COVER = ("assets/social-cover.jpg", 1200, 630, "Библиотека видео центра «Рама». Кришна и Арджуна на Курукшетре.")
MARK = "<!-- Generated by scripts/build_seo.py -->"
META = re.compile(r"<!-- seo:head -->.*?<!-- /seo:head -->", re.S)
DATA = re.compile(r"window\.RAMA_DB = (.*);\s*", re.S)
ID = re.compile(r"[A-Za-z0-9_-]+\Z")


def video_path(key):
    return f"video/{key}/"


def topic_path(key):
    return ("seminars/" if "seminar" in key.split("-") else "topics/") + key + "/"


def link(path, label):
    return f'<a href="{escape(PATH + path)}">{escape(label)}</a>'


def listing(entries):
    return "<ul>" + "".join(f"<li>{entry}</li>" for entry in entries) + "</ul>"


def share(path, title, current=False):
    return (f'<button type="button"{(" data-current-share" if current else "")} '
            f'data-share-url="{escape(PATH + path)}" data-share-title="{escape(title)}">Поделиться</button>')


def schema_json(graph):
    data = json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False, separators=(",", ":"))
    return '<script type="application/ld+json">' + data.replace("<", "\\u003c") + "</script>"


def metadata(path, title, description, graph, image=COVER, kind="website", index=True):
    url = BASE + path
    img, width, height, alt = image
    tags = [f"<title>{escape(title)}</title>"]
    named = {
        "description": description, "robots": "index,follow,max-image-preview:large" if index else "noindex,follow",
        "twitter:card": "summary_large_image", "twitter:title": title, "twitter:description": description,
        "twitter:image": BASE + img, "twitter:image:alt": alt,
    }
    og = {
        "og:title": title, "og:description": description, "og:type": kind, "og:url": url,
        "og:site_name": SITE, "og:locale": "ru_RU", "og:image": BASE + img, "og:image:secure_url": BASE + img,
        "og:image:type": "image/jpeg", "og:image:width": str(width), "og:image:height": str(height), "og:image:alt": alt,
    }
    for attr, values in (("name", named), ("property", og)):
        tags.extend(f'<meta {attr}="{key}" content="{escape(value)}">' for key, value in values.items())
    tags.extend([f'<link rel="canonical" href="{url}">', f'<link rel="icon" sizes="32x32" href="{PATH}assets/favicon.png">',
                 f'<link rel="apple-touch-icon" href="{PATH}assets/apple-touch-icon.png">'])
    if graph:
        tags.append(schema_json(graph))
    return "\n".join(tags)


def item_list(entries):
    return {"@type": "ItemList", "numberOfItems": len(entries), "itemListElement": [
        {"@type": "ListItem", "position": n, "name": title, "url": BASE + path}
        for n, (path, title) in enumerate(entries, 1)]}


def timestamp(seconds):
    return f"{seconds//3600:02}:{seconds//60%60:02}:{seconds%60:02}"


def get_thumbnail(job):
    """Store only actual YouTube covers. The CDN can return tiny JPEG placeholders."""
    vid, folder = job
    from PIL import Image
    path = folder / f"{vid}.jpg"
    try:
        with urlopen(f"https://i.ytimg.com/vi/{vid}/hqdefault.jpg", timeout=8) as response:
            data = response.read(2_000_001)
        if len(data) > 2_000_000:
            return False
        with Image.open(BytesIO(data)) as img:
            if img.format != "JPEG" or img.size != (480, 360):
                path.unlink(missing_ok=True)
                return False
            img.verify()
        path.write_bytes(data)
        return True
    except HTTPError as error:
        if error.code in (404, 410):
            path.unlink(missing_ok=True)
        return False
    except (OSError, ValueError):
        return False


def build(out, fetch=False):
    source = (ROOT / "index.html").read_text()
    db = json.loads(DATA.fullmatch((ROOT / "assets/catalog.js").read_text())[1])
    videos = {v["id"]: v for v in db["videos"]}
    cats = {c["id"]: c for c in db["categories"] if c["active"]}
    sections = {s["id"]: s for s in db["sections"]}
    keys = [*videos, *cats, *sections, *(i["id"] for i in db["items"])]
    if not all(ID.fullmatch(k) for k in keys):
        raise ValueError("Unsupported catalog ID in URL")
    by_video, by_topic = defaultdict(list), defaultdict(list)
    for row in db["items"]:
        by_video[row["video"]].append(row)
        if row["type"] != "service":
            for cat in row["cats"]:
                by_topic[cat].append(row)
    cats = {c: row for c, row in cats.items() if by_topic[c]}
    out.mkdir(parents=True, exist_ok=True)
    if out != ROOT:
        shutil.copytree(ROOT / "assets", out / "assets", dirs_exist_ok=True)
        # Retain genuine ownership verification files supplied by the owner.
        for file in ROOT.glob("google*.html"):
            if re.fullmatch(r"google[0-9a-zA-Z_-]+\.html", file.name) and file.read_text().strip() == "google-site-verification: " + file.name:
                shutil.copy2(file, out / file.name)
        bing = ROOT / "BingSiteAuth.xml"
        if bing.is_file():
            shutil.copy2(bing, out / bing.name)
    thumbs = out / "assets" / "video-covers"
    if fetch:
        thumbs.mkdir(exist_ok=True)
        with ThreadPoolExecutor(max_workers=6) as pool:
            success = sum(pool.map(get_thumbnail, ((k, thumbs) for k in videos)))
        print(f"YouTube covers retrieved: {success}/{len(videos)}")
    for file in thumbs.glob("*.jpg"):
        if file.stem not in videos:
            file.unlink()

    def cover(vid):
        if (thumbs / (vid + ".jpg")).is_file():
            return ("assets/video-covers/" + vid + ".jpg", 480, 360, "Обложка видео «" + videos[vid]["title"] + "»")
        return COVER

    paths = [""]
    def page(path, heading, title, description, body, parents=(), entity=None, image=COVER, watch=False, index=True):
        crumbs = [("", "Главная"), *parents, (path, heading)]
        breadcrumb = {"@type": "BreadcrumbList", "@id": BASE + path + "#breadcrumbs", "itemListElement": [
            {"@type": "ListItem", "position": n, "name": label, "item": BASE + route}
            for n, (route,label) in enumerate(crumbs, 1)]}
        webpage = {"@type": "WebPage" if watch or not index else "CollectionPage", "@id": BASE + path + "#page",
                   "url": BASE + path, "name": heading, "description": description, "inLanguage": "ru",
                   "isPartOf": {"@id": BASE + "#website"}, "breadcrumb": {"@id": breadcrumb["@id"]}}
        graph = [webpage, breadcrumb]
        if entity:
            entity["@id"] = BASE + path + ("#video" if watch else "#list")
            webpage["mainEntity"] = {"@id": entity["@id"]}
            graph.append(entity)
        meta = metadata(path, title, description, graph if index else [], image,
                        "video.other" if watch else "website", index)
        nav = " / ".join(link(p,t) for p,t in crumbs[:-1])
        html = f"""<!doctype html>
<html lang="ru" class="seo"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
{meta}
<link rel="stylesheet" href="{PATH}assets/seo.css">
<script>try{{document.documentElement.classList.toggle('light',localStorage.getItem('rama-theme')==='light')}}catch{{}}</script>
<script defer src="{PATH}assets/share.js"></script></head><body class="seo-page">{MARK}
<header>{link("", SITE)} {link("videos/", "Все видео")} {link("topics/", "Темы")}</header>
<main><nav aria-label="Путь к странице">{nav}</nav><h1>{escape(heading)}</h1>{body}</main>
<footer>{link("", "Поиск по видеотеке")}</footer></body></html>"""
        if index:
            # Keep static snapshots usable at a local root and at the Pages project subpath.
            prefix = "../" * len(Path(path).parts)
            html = html.replace('="'+PATH, '="'+prefix)
        target = out / path if not index else out / path / "index.html"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(html)
        if index:
            paths.append(path)

    site_graph = [{"@type": "Organization", "@id": BASE + "#organization", "name": SITE, "url": BASE},
                  {"@type": "WebSite", "@id": BASE + "#website", "name": HOME_TITLE, "url": BASE,
                   "inLanguage": "ru", "publisher": {"@id": BASE + "#organization"}},
                  {"@type": "WebPage", "@id": BASE + "#page", "url": BASE, "name": HOME_TITLE,
                   "description": HOME_DESC, "isPartOf": {"@id": BASE + "#website"}, "inLanguage":"ru"}]
    home_meta = metadata("", HOME_TITLE, HOME_DESC, site_graph).replace('href="'+PATH+'assets/', 'href="assets/')
    if META.search(source) is None:
        raise ValueError("Missing home metadata markers")
    (out / "index.html").write_text(META.sub(lambda _: "<!-- seo:head -->\n"+home_meta+"\n<!-- /seo:head -->", source))
    sorted_videos = sorted(videos.values(), key=lambda v:v["date"] or "", reverse=True)
    entries = [(video_path(v["id"]),v["title"]) for v in sorted_videos]
    page("videos/", "Все видео", "Все видео по дате публикации · " + SITE,
         f"Полный каталог видеотеки центра «Рама». {len(videos)} выпусков с датами, описаниями и ссылками на главы.",
         listing(f'<time>{escape(v["date"] or "")}</time> · '+link(video_path(v["id"]),v["title"]) for v in sorted_videos),
         entity=item_list(entries))
    section_entries = [("sections/"+sid+"/", s["name"]) for sid,s in sections.items() if any(c["section"]==sid for c in cats.values())]
    page("topics/", "Тематические разделы", "Тематический указатель · " + SITE,
         "Разделы видеотеки о варнашраме, сознании Кришны, шастрах и современных общественных вопросах.",
         listing(link(p,t) for p,t in section_entries), entity=item_list(section_entries))

    duplicates = Counter(v["title"] for v in videos.values())
    for vid, v in videos.items():
        path = video_path(vid)
        title = v["title"]
        identity = title if duplicates[title] == 1 else f'{title} · выпуск {v["number"]}'
        items = sorted(by_video[vid],key=lambda i:(i["seconds"] is None,i["seconds"] or 0))
        topics = list(dict.fromkeys(c for i in items for c in i["cats"] if c in cats))
        descriptions = [text.strip() for text in v["descriptions"] if text.strip()]
        dated = [i for i in items if i["seconds"] is not None]
        examples = [i["title"] for i in items if i["type"] != "service" and i["title"] != title]
        detail = next((t for t in descriptions if len(t)>65 and t!=title), None) or next(iter(examples), None)
        if not detail:
            detail = ", ".join(cats[c]["name"] for c in topics) or "Полная запись выпуска"
        desc = f'{identity}. {detail}'
        if len(desc)>195:
            desc = desc[:194].rsplit(" ",1)[0]+"…"
        yt = f"https://www.youtube.com/watch?v={vid}"
        embed = f"https://www.youtube-nocookie.com/embed/{vid}"
        image = cover(vid)
        video = {"@type": "VideoObject", "name": title, "description": desc, "inLanguage": "ru",
                 "url": BASE+path, "embedUrl": embed, "thumbnailUrl": BASE+image[0] if image!=COVER else f"https://i.ytimg.com/vi/{vid}/hqdefault.jpg",
                 "about": [cats[c]["name"] for c in topics]}
        date_text = v["date"]
        if date_text:
            video["uploadDate"] = date.fromisoformat(date_text).isoformat()
        body = [f'<iframe class="watch-player" loading="lazy" title="{escape(title)}" src="{embed}" width="800" height="450" allow="encrypted-media; picture-in-picture; fullscreen" allowfullscreen></iframe>',
                '<p data-current-chapter aria-live="polite"></p>',
                f'<div class="tools"><time>{escape(date_text or "")}</time><a data-youtube href="{yt}">Открыть на YouTube</a>{share(path,title,True)}</div>']
        if topics:
            body.append('<h2>Темы выпуска</h2><nav aria-label="Темы выпуска">'+" · ".join(link(topic_path(c),cats[c]["name"]) for c in topics)+'</nav>')
        if descriptions:
            body.append('<h2>Описание</h2>'+''.join(f"<p>{escape(t)}</p>" for t in descriptions))
        if items:
            body.append('<h2>Материалы выпуска</h2><ol class="chapter-list">')
        clips = []
        for n,row in enumerate(items):
            name,sec = row["title"],row["seconds"]
            if sec is None:
                body.append(f'<li id="{row["id"]}">{escape(name)}</li>')
                continue
            moment = path + f'?t={sec}'
            body.append(f'<li id="{row["id"]}" data-seconds="{sec}"><a class="time-link" href="{PATH+moment}">{timestamp(sec)}</a> '
                        f'<span class="chapter-name">{escape(name)}</span> · <a class="youtube-time" href="{yt}&amp;t={sec}s">YouTube</a> '
                        f'{share(moment,name)}</li>')
            if n+1 < len(dated) and row["type"]!="service" and dated[n+1]["seconds"]>sec:
                clips.append({"@type":"Clip","name":name,"startOffset":sec,"endOffset":dated[n+1]["seconds"],"url":BASE+moment})
        if clips:
            video["hasPart"] = clips
        if items:
            body.append("</ol>")
        refs = [r for r in v["references"] if urlsplit(r["url"]).scheme in ("https","http")]
        if refs:
            body.append("<h2>Дополнительные источники</h2>"+listing(f'<a href="{escape(r["url"])}">{escape(r.get("text") or r["url"])}</a>' for r in refs))
        body.append(f'<script src="{PATH}assets/watch.js"></script>')
        page(path,title,identity+" · Видеотека «Рама»",desc,"".join(body),[("videos/","Все видео")],video if date_text else None,image,True)

    for secpath, name in section_entries:
        sid = secpath.split("/")[1]
        entries = [(topic_path(k),c["name"]) for k,c in cats.items() if c["section"]==sid]
        desc = f'{name}. Тематические подборки видеотеки: '+", ".join(t for _,t in entries[:3])+"."
        page(secpath,name,name+" · Раздел видеотеки «Рама»",desc,share(secpath,name)+listing(link(p,t) for p,t in entries),
             [("topics/","Темы")],item_list(entries))
    for key, cat in cats.items():
        path, title = topic_path(key),cat["name"]
        groups = defaultdict(list)
        for row in by_topic[key]:
            groups[row["video"]].append(row)
        entries = [(video_path(v["id"]),v["title"]) for v in sorted_videos if v["id"] in groups]
        desc = f'{title}. Материалов в подборке: {len(by_topic[key])}. Выпуски и тематические фрагменты центра «Рама» с переходами к записи.'
        parents = [("topics/","Темы"),("sections/"+cat["section"]+"/",sections[cat["section"]]["name"])]
        if cat["parent"] in cats:
            parents.append((topic_path(cat["parent"]),cats[cat["parent"]]["name"]))
        body = [f'<div class="tools">{share(path,title)}{link("#cat="+key,"Открыть с фильтрами")}</div>']
        children = [c for c in cats.values() if c["parent"]==key]
        if children:
            body.append("<h2>Подтемы</h2>"+listing(link(topic_path(c["id"]),c["name"]) for c in children))
        for v in sorted_videos:
            if v["id"] not in groups:
                continue
            vp = video_path(v["id"])
            body.append("<h2>"+link(vp,v["title"])+"</h2>")
            def chapter(row):
                sec = row["seconds"]
                return link(vp+(f"?t={sec}" if sec is not None else "#"+row["id"]),
                            (timestamp(sec)+" · " if sec is not None else "")+row["title"])
            body.append(listing(chapter(row) for row in sorted(groups[v["id"]],key=lambda r:r["seconds"] or 0)))
        image = COVER
        if path.startswith("seminars/"):
            image = next((cover(k) for k in groups if cover(k)!=COVER), COVER)
        page(path,title,title+" · Тематическая видеотека",desc,"".join(body),parents,item_list(entries),image)
    page("404.html","Страница не найдена","Страница не найдена · "+SITE,"Перейдите к поиску или каталогу видео.",
         f'<p>Проверьте адрес или откройте {link("videos/","каталог видео")}.</p>',index=False)
    ns = "http://www.sitemaps.org/schemas/sitemap/0.9"
    tree = ET.Element("urlset",xmlns=ns)
    for path in paths:
        ET.SubElement(ET.SubElement(tree,"url"),"loc").text = BASE+path
    ET.indent(tree)
    ET.ElementTree(tree).write(out/"sitemap.xml", encoding="utf-8",xml_declaration=True)
    (out/"robots.txt").write_text("User-agent: *\nAllow: /rama-db/\n\nSitemap: "+BASE+"sitemap.xml\n")
    (out/".nojekyll").touch()
    # Prune previously generated routes only. Other files in the repository belong to the owner.
    for folder in ("video","videos","topics","sections","seminars"):
        for file in (out/folder).rglob("index.html"):
            route = file.parent.relative_to(out).as_posix()+"/"
            if route not in paths and MARK in file.read_text():
                file.unlink()
    print(f"{len(paths)} indexable pages, {len(videos)} videos, {len(cats)} topics.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=ROOT/"_site")
    parser.add_argument("--fetch-thumbnails", action="store_true", help="Download verified JPEG covers (requires Pillow)")
    args = parser.parse_args()
    build(args.out.resolve(), args.fetch_thumbnails)
